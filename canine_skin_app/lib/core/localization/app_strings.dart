  static String of(BuildContext context, String key) {
    // localeOf() makes every screen rebuild when the language changes.
    final code = Localizations.localeOf(context).languageCode;
    return _values[code]?[key] ?? _values['en']?[key] ?? key;
  }

  /// Translates a disease name coming from the backend, e.g. "Mange".
  /// Matches on the first word, so "Fungal (Dandruff)" -> disease_Fungal.
  static String disease(BuildContext context, String? raw) {
    if (raw == null || raw.isEmpty) return of(context, 'unknown');
    final firstWord = raw.split(RegExp(r'[\s(_]')).first;
    final key = 'disease_$firstWord';
    final result = of(context, key);
    return result == key ? raw : result; // fall back to the original text
  }
